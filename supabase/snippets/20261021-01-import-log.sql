-- 2026-10-21 新增旁路表 hentai_import_log：标记「该用户的这条归档来自本地 zip 补录」
--
-- 背景：
--   本地已下载的 1303 个 ehviewer 画廊 zip 需要补录进 hentai_archive（status=200），
--   同时又要在库内能筛选/统计「哪些归档是补录的」。
--
-- 为什么是旁路表而不是给 hentai_archive_event 加 source 列：
--   1. event 的 unique 是 (user_id, gallery_id, status)，同画廊同状态只有一行，
--      加 source 会把「来源」和「水位线」绑死，后续任何一次线上写入都会把标记覆盖掉；
--   2. event 是判重链路的真值表，改它要连带改视图与 upsert_hentai_archive（含 private definer），
--      风险面远大于收益；
--   3. 本表是用户私有数据，可以直连 PostgREST 读写（与 event 表同范式），无需 definer 函数。
--
-- 语义边界（重要）：
--   - 本表只记录「补录事实」，不参与任何判重。判重口径仍是 title_hash + date。
--   - 唯一键 (user_id, title_hash)：语义是幂等布尔「这条归档是否被补录过」，
--     重复导入不会膨胀；batch_id 只表示「最近一次写入它的批次」。
--   - 删除本表行 = 撤销补录标记，不会动 hentai_archive_event（归档本身仍在）。
--   - 关联口径：title_hash 是 sha256(写入 RPC 的最终标题)，前端必须用同一个
--     字符串（realTitle.trim().slice(0,255)）算 hash，否则 join 不上。
--
-- 执行身份：表 owner（Supabase Dashboard SQL Editor 即 postgres）。
-- 验证：执行完跑 20261021-02-import-log-verify.sql。
-- 回滚：drop table if exists public.hentai_import_log;

begin;

-- ---------------------------------------------------------------- 1. 表
create table public.hentai_import_log (
  id            bigint generated by default as identity primary key,
  user_id       uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  title_hash    varchar(64) not null,
  title         varchar(255) not null,
  file_name     text        not null,
  file_mtime    timestamptz not null,
  gid           bigint      not null default 0,
  status        bigint      not null default 200,
  batch_id      uuid        not null default gen_random_uuid(),
  imported_time timestamptz not null default now(),
  constraint hentai_import_log_title_hash_format check (title_hash ~ '^[0-9a-f]{64}$'),
  constraint hentai_import_log_title_not_empty  check (btrim(title) <> ''),
  constraint hentai_import_log_file_not_empty   check (btrim(file_name) <> ''),
  constraint hentai_import_log_status_domain    check (status in (200, 304, 400)),
  constraint hentai_import_log_gid_not_negative check (gid >= 0),
  constraint hentai_import_log_user_id_title_hash_unique unique (user_id, title_hash)
);

comment on table public.hentai_import_log is
  '本地补录标记：与 hentai_archive 按 (user_id, title_hash) 关联，仅用于筛选/统计，不参与判重';
comment on column public.hentai_import_log.title_hash is
  '与 hentai_gallery.title_hash 同口径：sha256(写入 RPC 的最终标题)，前端需用同一字符串计算';
comment on column public.hentai_import_log.title is
  '写库时标题快照，便于不 join 归档表也能人工核对';
comment on column public.hentai_import_log.file_name is
  '来源 zip 的原始文件名（含扩展名），用于回溯到本地文件';
comment on column public.hentai_import_log.file_mtime is
  'zip 的 lastModified，即本次写入归档时使用的水位线 date';
comment on column public.hentai_import_log.gid is
  '本次实际传给 upsert_hentai_archive 的 gid（站点真实值，缺失为 0）';
comment on column public.hentai_import_log.status is
  '本次写入归档的 status，补录固定 200；保留域约束以便将来复用';
comment on column public.hentai_import_log.batch_id is
  '最近一次写入该行的导入批次；按批次撤销标记时使用（重复导入会迁移到新批次）';

-- 按批次统计/撤销的查询路径
create index hentai_import_log_user_id_batch_id_idx
  on public.hentai_import_log (user_id, batch_id);

-- ---------------------------------------------------------------- 2. RLS
alter table public.hentai_import_log enable row level security;

-- 谓词必须用 (select auth.uid()) 的 InitPlan 形式：auth.uid() 直接写在 USING 里会被当逐行表达式，
-- 每扫一行调一次 current_setting()（auth_rls_initplan 告警）。与 20261020-04 的 event 表口径一致。
create policy "Enable users to crud their own import log" on public.hentai_import_log
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------- 3. 授权
-- 用户私有数据：允许直连增删改（撤销标记需要 delete），但整表只对本人的行可见。
-- anon 一律不给：本表记录的是登录用户的私有清单。
--
-- 必须显式 GRANT：Supabase 自 2026-10-30 起对所有项目撤销「新表自动暴露到 Data API」的默认授权，
-- 未显式授权的对象在 PostgREST 上会被 42501 拒绝。显式 GRANT 即是官方要求的 opt-in 方式，
-- 与上面的 RLS 构成两层控制：GRANT 决定能否触达该对象，RLS 决定能触达哪些行。
revoke all on public.hentai_import_log from anon;
grant select, insert, update, delete on public.hentai_import_log to authenticated;

-- ---------------------------------------------------------------- 4. 断言
do $$
declare
  v_policies    int;
  v_qual        text;
  v_check       text;
  v_default     text;
begin
  if to_regclass('public.hentai_import_log') is null then
    raise exception 'hentai_import_log 未创建';
  end if;

  -- 列
  if exists (
    select 1
    from (values ('id'), ('user_id'), ('title_hash'), ('title'), ('file_name'),
                 ('file_mtime'), ('gid'), ('status'), ('batch_id'), ('imported_time')) as c(name)
    where not exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'hentai_import_log' and column_name::text = c.name
    )
  ) then
    raise exception 'hentai_import_log 缺少必需列';
  end if;

  -- 约束
  if not exists (select 1 from pg_constraint
                  where conrelid = 'public.hentai_import_log'::regclass
                    and conname = 'hentai_import_log_user_id_title_hash_unique') then
    raise exception '缺少唯一键 (user_id, title_hash)';
  end if;
  if (select count(*) from pg_constraint
       where conrelid = 'public.hentai_import_log'::regclass and contype = 'c') <> 5 then
    raise exception 'CHECK 约束数量不符（预期 5 条）';
  end if;

  -- 默认值：user_id 必须是 auth.uid()，否则 RLS 的 with check 会拒绝插入
  select column_default into v_default
  from information_schema.columns
  where table_schema = 'public' and table_name = 'hentai_import_log' and column_name = 'user_id';
  if v_default is null or v_default not like '%auth.uid()%' then
    raise exception 'user_id 默认值不是 auth.uid()：%', coalesce(v_default, 'null');
  end if;

  -- 索引
  if not exists (select 1 from pg_indexes
                  where schemaname = 'public' and tablename = 'hentai_import_log'
                    and indexname = 'hentai_import_log_user_id_batch_id_idx') then
    raise exception '缺少 (user_id, batch_id) 索引';
  end if;

  -- RLS + 策略
  if not (select relrowsecurity from pg_class where oid = 'public.hentai_import_log'::regclass) then
    raise exception 'hentai_import_log 未启用 RLS';
  end if;

  select count(*) into v_policies
  from pg_policies
  where schemaname = 'public' and tablename = 'hentai_import_log';
  if v_policies <> 1 then
    raise exception '策略数应为 1，实际 %', v_policies;
  end if;

  select pg_get_expr(polqual, polrelid), pg_get_expr(polwithcheck, polrelid)
    into v_qual, v_check
  from pg_policy
  where polrelid = 'public.hentai_import_log'::regclass
    and polname = 'Enable users to crud their own import log';
  if v_qual is null or v_check is null then
    raise exception '策略缺少 USING 或 WITH CHECK：% / %', v_qual, v_check;
  end if;
  -- InitPlan 形态（子查询形式）；逐行的 auth.uid() = user_id 会被判失败
  if v_qual not like '%SubPlan%' and v_qual not like '%SELECT auth.uid()%' then
    raise exception 'USING 未使用 (select auth.uid()) 形式：%', v_qual;
  end if;
  if v_check not like '%SubPlan%' and v_check not like '%SELECT auth.uid()%' then
    raise exception 'WITH CHECK 未使用 (select auth.uid()) 形式：%', v_check;
  end if;

  -- 授权
  if not has_table_privilege('authenticated', 'public.hentai_import_log', 'select')
     or not has_table_privilege('authenticated', 'public.hentai_import_log', 'insert')
     or not has_table_privilege('authenticated', 'public.hentai_import_log', 'update')
     or not has_table_privilege('authenticated', 'public.hentai_import_log', 'delete') then
    raise exception 'authenticated 授权不全（需 select/insert/update/delete）';
  end if;
  if has_table_privilege('anon', 'public.hentai_import_log', 'select')
     or has_table_privilege('anon', 'public.hentai_import_log', 'insert')
     or has_table_privilege('anon', 'public.hentai_import_log', 'update')
     or has_table_privilege('anon', 'public.hentai_import_log', 'delete') then
    raise exception 'anon 不应持有 hentai_import_log 的任何权限';
  end if;

  raise notice 'hentai_import_log 就绪：旁路补录标记表（不参与判重）';
end $$;

-- ---------------------------------------------------------------- 5. 让 PostgREST 重新加载 schema
notify pgrst, 'reload schema';

commit;

